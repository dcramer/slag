/**
 * Rebuilds src/core/name-filter/words.ts, the published word lists the name filter reads, from downloaded copies.
 * The game can't import a text file in every host, so the lists ship as a module; this keeps it a verbatim copy.
 *
 *   mkdir <an empty folder> and curl into it:
 *     https://raw.githubusercontent.com/LDNOOBW/List-of-Dirty-Naughty-Obscene-and-Otherwise-Bad-Words/<commit>/en
 *     https://raw.githubusercontent.com/dsojevic/profanity-list/<commit>/en.json
 *     https://raw.githubusercontent.com/dsojevic/profanity-list/<commit>/LICENSE
 *   pnpm tsx tools/name-words.ts <folder>/en <folder>/en.json <folder>/LICENSE <ldnoobw commit> <dsojevic commit>
 *
 * Then update the commits in public/ASSETS.md. Entries are selected by index in src/core/name-filter/index.ts, so
 * check its index sets against the new lists.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const [ldnoobwPath, dsojevicPath, dsojevicLicense, ldnoobwCommit, dsojevicCommit] = process.argv.slice(2);
if (!ldnoobwPath || !dsojevicPath || !dsojevicLicense || !ldnoobwCommit || !dsojevicCommit) {
  console.error('usage: pnpm tsx tools/name-words.ts <ldnoobw en> <dsojevic en.json> <dsojevic LICENSE> <ldnoobw commit> <dsojevic commit>');
  process.exit(1);
}

const ldnoobw = readFileSync(ldnoobwPath, 'utf8')
  .split('\n')
  .map((l) => l.trim())
  .filter(Boolean);

interface Raw {
  id: string;
  match: string;
  tags?: string[];
  severity: number;
  exceptions?: string[];
}
const dsojevic = (JSON.parse(readFileSync(dsojevicPath, 'utf8')) as Raw[]).map((e) => ({
  match: e.match,
  tags: e.tags ?? [],
  severity: e.severity,
  ...(e.exceptions?.length ? { exceptions: e.exceptions } : {}),
}));

const license = readFileSync(dsojevicLicense, 'utf8')
  .trim()
  .split('\n')
  .map((l) => ` * ${l}`.trimEnd())
  .join('\n');

const out = `// Generated by tools/name-words.ts from the lists credited in public/ASSETS.md. Don't edit by hand.

/**
 * "List of Dirty, Naughty, Obscene, and Otherwise Bad Words", English (\`en\`), commit ${ldnoobwCommit}:
 * https://github.com/LDNOOBW/List-of-Dirty-Naughty-Obscene-and-Otherwise-Bad-Words, CC BY 4.0. One entry per line, in order.
 */
export const LDNOOBW_EN: readonly string[] = ${JSON.stringify(ldnoobw)};

/** An entry of dsojevic/profanity-list: \`match\` is \`|\`-separated, \`*\` repeats the letter before it; severity 1 mild to 4 severe. */
export interface ListedWord {
  match: string;
  tags: string[];
  severity: number;
  /** Longer words the match hides in, \`*\` standing for the match. */
  exceptions?: string[];
}

/**
 * dsojevic/profanity-list, English (\`en.json\`, without its ids), commit ${dsojevicCommit}:
 * https://github.com/dsojevic/profanity-list. Its license:
 *
${license}
 */
export const DSOJEVIC_EN: readonly ListedWord[] = ${JSON.stringify(dsojevic)};
`;

const file = new URL('../src/core/name-filter/words.ts', import.meta.url).pathname;
writeFileSync(file, out);
execFileSync('pnpm', ['exec', 'oxfmt', file], { stdio: 'inherit' });
console.log(`${file}: ${ldnoobw.length} + ${dsojevic.length} entries`);
