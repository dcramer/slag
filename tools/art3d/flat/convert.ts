/**
 * A flat kind's frames (docs/CHARACTERS.md → Rendered kinds → Flat kinds) from the role map `rolemap.py`
 * made of its game-size design: the real tracer's parts, the drawing's interior lines, the cast's eyes
 * where the drawing's specks were. One still frame in every clip. Test stage, for the zapmouse:
 *   python3 tools/art3d/flat/rolemap.py art/sprites/zapmouse/design.png map.json map.png 21 9 12
 *   pnpm exec tsx tools/art3d/flat/convert.ts map.json src/render/cast/sprites/zapmouse/frames.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { trace } from '../page/trace';

const [src, out] = process.argv.slice(2);
const m = JSON.parse(readFileSync(src, 'utf8')) as {
  W: number;
  H: number;
  R: number;
  roles: string[];
  role: number[];
  height: number;
  lines: { role: number; pts: number[] }[];
};
const COLORS: Record<string, string> = { fur: '#f2c62a', dark: '#2a1f1a', cheek: '#e0473b', tin: '#c4c8ce', plug: '#e8e2d4', cord: '#7a5236' };
const settings = {
  step: 1e9,
  trace: { res: m.R, min: 0.8, eps: 0.22, smooth: 2 },
  roles: { fur: {}, dark: { min: 0.12 }, cheek: { min: 0.3 }, tin: {}, plug: { min: 0.35 } },
} as any;
const role = Int16Array.from(m.role);
const depth = new Float32Array(m.W * m.H);
const t = trace(role, depth, m.W, m.H, m.R, settings, m.roles);
// Back to front by role: the tail behind the body, the fills on top.
const ORDER = ['tin', 'fur', 'plug', 'cheek', 'dark'];
t.parts.sort((a, b) => ORDER.indexOf(m.roles[a.role]) - ORDER.indexOf(m.roles[b.role]));
// The drawing's own eyes and nose are specks at play size: the face kit draws the cast's eyes there instead.
const D = m.roles.indexOf('dark');
const area = (r: number[]) => {
  let a = 0;
  for (let i = 0; i < r.length; i += 2) {
    const j = (i + 2) % r.length;
    a += r[i] * r[j + 1] - r[j] * r[i + 1];
  }
  return Math.abs(a) / 2;
};
const mid = (r: number[]) => {
  let x = 0;
  let y = 0;
  for (let i = 0; i < r.length; i += 2) {
    x += r[i];
    y += r[i + 1];
  }
  return [x / (r.length / 2), y / (r.length / 2)];
};
const specks = t.parts.filter((p) => p.role === D && area(p.ring) < 0.6 && Math.abs(mid(p.ring)[1] + 12.5) < 2 && Math.abs(mid(p.ring)[0]) < 6);
for (const p of specks)
  console.log(
    'speck',
    area(p.ring).toFixed(2),
    mid(p.ring)
      .map((v) => v.toFixed(2))
      .join(','),
  );
t.parts = t.parts.filter((p) => !specks.includes(p));
// The cord belt in black reads as a frowning mouth at play size: it's a brown cable instead.
const roles = [...m.roles, 'cord'];
for (const p of t.parts) if (p.role === D && mid(p.ring)[1] > -10) p.role = roles.length - 1;
// Eyes are the two biggest specks, near (left, as it faces right) first; the nose speck goes too.
const eyes = specks
  .sort((a, b) => area(b.ring) - area(a.ring))
  .slice(0, 2)
  .map((p) => mid(p.ring))
  .sort((a, b) => a[0] - b[0]);

// The soles on the floor, the pen and its boil just under it: the map's bottom row is a cell under the drawing's lowest pixel.
let low = -0.15;
for (const r of t.sil) for (let i = 1; i < r.length; i += 2) low = Math.max(low, r[i] + 0.15);
const lift = (r: number[]) => r.map((v, i) => (i % 2 ? v - low : v));
t.sil = t.sil.map(lift);
for (const p of t.parts) p.ring = lift(p.ring);
for (const l of m.lines) l.pts = lift(l.pts);
for (const e of eyes) e[1] -= low;
const enc = (r: number[]) => {
  const a = new Int16Array(r.map((v) => Math.round(v * 8)));
  let s = '';
  for (const b of new Uint8Array(a.buffer)) s += String.fromCharCode(b);
  return Buffer.from(s, 'binary').toString('base64');
};
const mirror = (r: number[]) => {
  const o: number[] = [];
  for (let i = r.length - 2; i >= 0; i -= 2) o.push(-r[i], r[i + 1]);
  return o;
};
const frame = (flip: boolean) => {
  const f = (r: number[]) => enc(flip ? mirror(r) : r);
  const e = eyes.flatMap(([x, y], i) => [Math.round((flip ? -x : x) * 8), Math.round(y * 8), i ? 6 : 7]);
  return {
    eyes: e,
    head: [0, Math.round((eyes[0][1] - 1) * 8), 64, 0],
    sil: t.sil.map(f),
    parts: t.parts.map((p) => [p.role, f(p.ring)]),
    lines: m.lines.map((l) => [l.role, f(l.pts)]),
  };
};
const clip = (extra: object) => ({ loop: true, fps: 1, ...extra, r: [frame(false)], l: [frame(true)] });
const set = {
  kind: 'zapmouse',
  height: m.height,
  flat: true,
  face: { r: 0.85, iris: '#2a1f1a', mouth: [1.8, 1.6], eye: 'dot' },
  roles: roles.map((n) => ({ color: COLORS[n], ...(n === 'fur' ? { slot: 'player' } : {}) })),
  clips: {
    idle: clip({}),
    walk: clip({ stride: 36 }),
    run: clip({ stride: 56 }),
    air: clip({ vy: [-420, 420] }),
    wall: clip({}),
    cheer: clip({}),
    death: clip({ loop: false }),
  },
};
writeFileSync(
  out,
  `// Generated by tools/art3d/flat/convert.ts from art/sprites/zapmouse/design.png: do not edit.\nimport type { SpriteSet } from '../types';\n\nexport const sprites: SpriteSet = ${JSON.stringify(set)} as SpriteSet;\n`,
);
console.log('parts', t.parts.length, 'sil', t.sil.length, 'lines', m.lines.length);
