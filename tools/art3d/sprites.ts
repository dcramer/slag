/**
 * The 3D-to-2D pipeline's one command (tools/art3d/README.md):
 *
 *   pnpm sprites [kind …]                  trace every kind with settings (or the ones named) into the game
 *   pnpm sprites study KIND [--frames 16] [--clips a,b] [--from 0.3 --to 0.6] [--face]
 *                                          every animation in the model, sampled evenly, as a sheet
 *   pnpm sprites keys KIND [--keys a,b]    each keyed pose on its own, to set them from the pose sheet
 *   pnpm sprites inspect FILE.glb          a turnaround of a raw model, its clips and its texture's colours
 *
 * It serves tools/art3d/page/ with Vite, drives it in headless Chromium (the same browser the shot tools
 * use), and writes what the page hands back. Everything comes from what is checked in: the model and
 * `sprite.json` in art/sprites/<kind>/, and the code here.
 */
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';
import type { SpriteSet } from '../../src/render/cast/sprites/types';
import { argReader, launchBrowser } from '../lib/server';
import type { Settings } from './settings';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const argv = process.argv.slice(2);
const { opt, flag } = argReader(argv);
const words = argv.filter((a, i) => !a.startsWith('--') && !(i > 0 && argv[i - 1].startsWith('--') && !['--face'].includes(argv[i - 1])));
const shots = join(root, 'shots/art3d');

/** The game's frames for a kind, as a TypeScript module (generated: never edited by hand). */
function framesModule(set: SpriteSet): string {
  return `// Generated by \`pnpm sprites ${set.kind}\` (tools/art3d) from art/sprites/${set.kind}/: do not edit.
import type { SpriteSet } from '../types';

export const sprites: SpriteSet = ${JSON.stringify(set)};
`;
}

const vite = await createServer({
  root: join(root, 'tools/art3d/page'),
  configFile: false,
  logLevel: 'error',
  server: { port: 0, fs: { allow: [root] } },
  optimizeDeps: { include: ['three', 'three/examples/jsm/loaders/GLTFLoader.js', 'three/examples/jsm/libs/meshopt_decoder.module.js'] },
});
await vite.listen();
const addr = vite.httpServer!.address();
const base = `http://localhost:${typeof addr === 'object' && addr ? addr.port : 0}/`;
const browser = await launchBrowser();
const page = await browser.newPage();
const errors: string[] = [];
page.on('pageerror', (e: Error) => errors.push(String(e)));
page.on('console', (m) => {
  if (m.type() === 'error') errors.push(m.text());
  else if (process.env.ART3D_LOG) console.log('page:', m.text());
});

const fsUrl = (p: string) => `/@fs${resolve(p)}`;
const dataPng = (url: string) => Buffer.from(url.slice(url.indexOf(',') + 1), 'base64');
const settingsOf = (kind: string) => JSON.parse(readFileSync(join(root, 'art/sprites', kind, 'sprite.json'), 'utf8')) as Settings;
const modelUrl = (kind: string, s: Settings) => fsUrl(join(root, 'art/sprites', kind, s.model));
const render = (kind: string, s: Settings): Promise<SpriteSet> =>
  page.evaluate(([u, st, k]) => (window as any).art3d.render(u, st, k), [modelUrl(kind, s), s, kind] as const);
const sheet = (set: SpriteSet, zoom: number, opts: object = {}): Promise<string> =>
  page.evaluate(([st, z, o]) => (window as any).art3d.contact(st, z, o), [set, zoom, opts] as const);

async function done(code = 0) {
  await browser.close();
  await vite.close();
  if (errors.length) {
    console.error(errors.join('\n'));
    code ||= 1;
  }
  process.exit(code);
}

try {
  await page.goto(base);
  await page.waitForFunction(() => document.title === 'art3d ready', null, { timeout: 60_000 });
  mkdirSync(shots, { recursive: true });
  if (words[0] === 'inspect') {
    const file = words[1];
    const out = opt('out', join(shots, file.replace(/.*\//, '').replace(/\.glb$/, '') + '-turnaround.png'))!;
    const got = await page.evaluate(([u, k]) => (window as any).art3d.inspect(u, 512, k), [fsUrl(file), Number(opt('k', '14'))] as const);
    writeFileSync(out, dataPng(got.sheet));
    console.log(JSON.stringify({ clips: got.clips, swatches: got.swatches }));
    console.log(out);
  } else if (words[0] === 'study' || words[0] === 'keys') {
    const kind = words[1];
    const s = settingsOf(kind);
    if (words[0] === 'study') {
      const info = await page.evaluate((u) => (window as any).art3d.inspect(u, 64, 2), modelUrl(kind, s));
      const names: string[] = opt('clips')?.split(',') ?? info.clips.map((c: { name: string }) => c.name);
      const n = Number(opt('frames', '16'));
      s.clips = Object.fromEntries(
        names.map((c) => [c, { src: c, frames: n, loop: true, from: Number(opt('from', '0')), to: Number(opt('to', '1')), face: flag('face') }]),
      );
      console.log(info.clips.map((c: { name: string; seconds: number }) => `${c.name} ${c.seconds.toFixed(2)} s`).join('\n'));
    } else {
      const names = opt('keys')?.split(',') ?? Object.keys(s.keys ?? {});
      s.clips = Object.fromEntries(names.map((k) => [k, { keys: [k], frames: 1, loop: false }]));
    }
    const set = await render(kind, s);
    const out = join(shots, `${kind}-${words[0]}.png`);
    writeFileSync(out, dataPng(await sheet(set, Number(opt('zoom', words[0] === 'keys' ? '8' : '3')), { facings: words[0] === 'keys' ? ['r', 'l'] : ['r'] })));
    console.log(out);
  } else {
    const kinds = words.length ? words : readdirSync(join(root, 'art/sprites')).filter((k) => existsSync(join(root, 'art/sprites', k, 'sprite.json')));
    for (const kind of kinds) {
      const t0 = Date.now();
      const set = await render(kind, settingsOf(kind));
      const dest = join(root, 'src/render/cast/sprites', kind);
      mkdirSync(dest, { recursive: true });
      const file = join(dest, 'frames.ts');
      writeFileSync(file, framesModule(set));
      spawnSync(join(root, 'node_modules/.bin/oxfmt'), [file], { stdio: 'ignore' });
      writeFileSync(join(shots, `${kind}-frames.png`), dataPng(await sheet(set, Number(opt('zoom', '4')), { only: opt('only')?.split(',') })));
      writeFileSync(join(shots, `${kind}-rolls.png`), dataPng(await page.evaluate(([st]) => (window as any).art3d.rolls(st, 8), [set] as const)));
      writeFileSync(join(shots, `${kind}-silhouettes.png`), dataPng(await sheet(set, 1.67, { silhouette: true, facings: ['r'] })));
      const frames = Object.values(set.clips).reduce((a, c) => a + c.r.length + c.l.length, 0);
      console.log(
        `${kind}: ${frames} frames, ${(readFileSync(file).length / 1024).toFixed(0)} KB, ${((Date.now() - t0) / 1000).toFixed(1)} s; sheets: ${shots}/${kind}-{frames,silhouettes,rolls}.png`,
      );
    }
  }
} catch (e) {
  console.error(e);
  await done(1);
}
await done();
