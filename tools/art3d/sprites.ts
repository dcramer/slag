/**
 * The 3D-to-2D sprite pipeline's one command (tools/art3d/README.md):
 *
 *   pnpm sprites [kind …]                  render every kind with settings (or the ones named) into the game
 *   pnpm sprites study KIND [--frames 16]  every animation in the kind's model, sampled evenly, as a sheet
 *   pnpm sprites inspect FILE.glb          a turnaround of a raw model, its clips and its texture's colours
 *
 * It serves tools/art3d/page/ with Vite, drives it in headless Chromium (the same browser the shot tools
 * use), and writes what the page hands back. Everything comes from what is checked in: the model and
 * `sprite.json` in art/sprites/<kind>/, and the code here.
 */
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';
import { argReader, launchBrowser } from '../lib/server';
import { dropAlpha, optimisePng } from './png';
import type { Settings } from './settings';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const argv = process.argv.slice(2);
const { opt } = argReader(argv);
const words = argv.filter((a, i) => !a.startsWith('--') && !(i > 0 && argv[i - 1].startsWith('--')));
const shots = join(root, 'shots/art3d');

interface Frame {
  x: number;
  y: number;
  w: number;
  h: number;
  ax: number;
  ay: number;
}
interface Atlas {
  scale: number;
  png: string;
  masks: string;
  w: number;
  h: number;
  clips: Record<string, Record<'r' | 'l', Frame[]>>;
}

/** The game's frame table for a kind, as a TypeScript module (generated: never edited by hand). */
function framesModule(kind: string, s: Settings, play: Atlas, card: Atlas | null): string {
  const clips = (atlas: Atlas) =>
    Object.fromEntries(
      Object.entries(s.clips)
        .filter(([name]) => atlas.clips[name])
        .map(([name, c]) => [
          name,
          {
            loop: c.loop,
            ...(c.fps ? { fps: c.fps } : {}),
            ...(c.stride ? { stride: c.stride } : {}),
            ...(c.vy ? { vy: c.vy } : {}),
            ...(c.holds ? { holds: c.holds } : {}),
            r: atlas.clips[name].r.map((f) => [f.x, f.y, f.w, f.h, f.ax, f.ay]),
            l: atlas.clips[name].l.map((f) => [f.x, f.y, f.w, f.h, f.ax, f.ay]),
          },
        ]),
    );
  const sheet = (name: string, atlas: Atlas | null) =>
    atlas
      ? `{ scale: ${atlas.scale}, w: ${atlas.w}, h: ${atlas.h}, png: new URL('./${name}.png', import.meta.url).href, mask: new URL('./${name}-mask.png', import.meta.url).href, clips: ${JSON.stringify(clips(atlas))} }`
      : 'null';
  const slots = Object.fromEntries(Object.values(s.roles).flatMap((r) => (r.slot ? [[r.slot, r.color]] : [])));
  return `// Generated by \`pnpm sprites ${kind}\` (tools/art3d) from art/sprites/${kind}/: do not edit.
import type { SpriteSet } from '../types';

export const sprites: SpriteSet = {
  kind: '${kind}',
  height: ${s.height},
  slots: ${JSON.stringify(slots)},
  play: ${sheet('play', play)},
  card: ${sheet('card', card)},
};
`;
}

const vite = await createServer({
  root: join(root, 'tools/art3d/page'),
  configFile: false,
  logLevel: 'error',
  server: { port: 0, fs: { allow: [root] } },
  optimizeDeps: {
    include: ['three', 'three/examples/jsm/loaders/GLTFLoader.js', 'three/examples/jsm/libs/meshopt_decoder.module.js'],
  },
});
await vite.listen();
const addr = vite.httpServer!.address();
const base = `http://localhost:${typeof addr === 'object' && addr ? addr.port : 0}/`;
const browser = await launchBrowser();
const page = await browser.newPage();
const errors: string[] = [];
page.on('pageerror', (e: Error) => errors.push(String(e)));
page.on('console', (m) => {
  if (m.type() === 'error') errors.push(m.text());
  else if (process.env.ART3D_LOG) console.log('page:', m.text());
});

const fsUrl = (p: string) => `/@fs${resolve(p)}`;
const dataPng = (url: string) => Buffer.from(url.slice(url.indexOf(',') + 1), 'base64');
const settingsOf = (kind: string) => JSON.parse(readFileSync(join(root, 'art/sprites', kind, 'sprite.json'), 'utf8')) as Settings;
const modelUrl = (kind: string, s: Settings) => fsUrl(join(root, 'art/sprites', kind, s.model));
const render = (url: string, s: Settings): Promise<{ play: Atlas; card: Atlas | null }> =>
  page.evaluate(([u, st]) => (window as any).art3d.renderSprites(u, st), [url, s] as const);
const sheetOf = (atlas: Atlas, zoom: number, smooth: boolean, facings: string[]): Promise<string> =>
  page.evaluate(([a, z, sm, f]) => (window as any).art3d.contact(a, z, sm, f), [atlas, zoom, smooth, facings] as const);

async function done(code = 0) {
  await browser.close();
  await vite.close();
  if (errors.length) {
    console.error(errors.join('\n'));
    code ||= 1;
  }
  process.exit(code);
}

try {
  await page.goto(base);
  await page.waitForFunction(() => document.title === 'art3d ready', null, { timeout: 60_000 });
  mkdirSync(shots, { recursive: true });
  if (words[0] === 'inspect') {
    const file = words[1];
    const out = opt('out', join(shots, file.replace(/.*\//, '').replace(/\.glb$/, '') + '-turnaround.png'))!;
    const got = await page.evaluate(([u, k]) => (window as any).art3d.inspect(u, 512, k), [fsUrl(file), Number(opt('k', '14'))] as const);
    writeFileSync(out, dataPng(got.sheet));
    console.log(JSON.stringify({ clips: got.clips, swatches: got.swatches }));
    console.log(out);
  } else if (words[0] === 'study') {
    const kind = words[1];
    const s = settingsOf(kind);
    const info = await page.evaluate((u) => (window as any).art3d.inspect(u, 64, 2), modelUrl(kind, s));
    const names: string[] = opt('clips')?.split(',') ?? info.clips.map((c: { name: string }) => c.name);
    const n = Number(opt('frames', '16'));
    s.clips = Object.fromEntries(
      names.map((c) => [c, { src: c, frames: n, loop: true, from: Number(opt('from', '0')), to: Number(opt('to', '1')), face: argv.includes('--face') }]),
    );
    const got = await render(modelUrl(kind, s), s);
    const out = join(shots, `${kind}-study.png`);
    writeFileSync(out, dataPng(await sheetOf(got.play, Number(opt('zoom', '2')), true, ['r'])));
    console.log(info.clips.map((c: { name: string; seconds: number }) => `${c.name} ${c.seconds.toFixed(2)} s`).join('\n'));
    console.log(out);
  } else {
    const kinds = words.length ? words : readdirSync(join(root, 'art/sprites')).filter((k) => existsSync(join(root, 'art/sprites', k, 'sprite.json')));
    for (const kind of kinds) {
      const s = settingsOf(kind);
      const t0 = Date.now();
      const got = await render(modelUrl(kind, s), s);
      const dest = join(root, 'src/render/cast/sprites', kind);
      mkdirSync(dest, { recursive: true });
      let bytes = 0;
      for (const [name, atlas] of [
        ['play', got.play],
        ['card', got.card],
      ] as const) {
        if (!atlas) continue;
        const png = optimisePng(dataPng(atlas.png));
        const masks = optimisePng(dropAlpha(dataPng(atlas.masks)));
        writeFileSync(join(dest, `${name}.png`), png);
        writeFileSync(join(dest, `${name}-mask.png`), masks);
        bytes += png.length + masks.length;
        console.log(`${kind} ${name}: ${atlas.w}×${atlas.h} px, ${(png.length / 1024).toFixed(0)} KB + mask ${(masks.length / 1024).toFixed(0)} KB`);
        writeFileSync(join(shots, `${kind}-${name}.png`), dataPng(await sheetOf(atlas, name === 'play' ? 4 : 1, false, ['r', 'l'])));
      }
      writeFileSync(join(dest, 'frames.ts'), framesModule(kind, s, got.play, got.card));
      spawnSync(join(root, 'node_modules/.bin/oxfmt'), [join(dest, 'frames.ts')], { stdio: 'inherit' });
      console.log(`${kind}: ${((Date.now() - t0) / 1000).toFixed(1)} s, ${(bytes / 1024).toFixed(0)} KB in all; sheets: ${shots}/${kind}-{play,card}.png`);
    }
  }
} catch (e) {
  console.error(e);
  await done(1);
}
await done();
